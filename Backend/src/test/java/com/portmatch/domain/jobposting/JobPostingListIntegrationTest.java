@DataJpaTest(showSql = false, properties = {
        "spring.flyway.enabled=false", "spring.sql.init.mode=never", "spring.jpa.hibernate.ddl-auto=none"
})
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@Import({JobPostingServiceImpl.class, CompanyServiceImpl.class, QuerydslConfig.class,
        JobPostingListIntegrationTest.SqlCaptureConfig.class})
@Testcontainers
class JobPostingListIntegrationTest {
    private static final String LIST_URL = "/api/job-postings";
    private static final ZoneId SEOUL = ZoneId.of("Asia/Seoul");

    @Container
    static final PostgreSQLContainer<?> DB = new PostgreSQLContainer<>(
            DockerImageName.parse("pgvector/pgvector:pg17").asCompatibleSubstituteFor("postgres"))
            .withInitScript("db/view-count-init.sql");

    @DynamicPropertySource
    static void database(DynamicPropertyRegistry registry) {
        registry.add("spring.datasource.url", DB::getJdbcUrl);
        registry.add("spring.datasource.username", DB::getUsername);
        registry.add("spring.datasource.password", DB::getPassword);
    }

    @MockitoBean JobPostingEmbeddingService embeddingService;
    @Autowired JobPostingService service;
    @Autowired JdbcTemplate jdbc;
    @Autowired EntityManager entityManager;
    @Autowired SqlCapture sqlCapture;
    private MockMvc mvc;

    @BeforeEach
    void setUp() {
        jdbc.execute("""
                CREATE TABLE companies (
                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    cid varchar(255) UNIQUE, companies_name varchar(500), address text, size varchar(500),
                    homepage_url text, tot_psncnt varchar(100), yr_sales_amt varchar(100),
                    busi_cont text, logo text, user_id bigint
                )
                """);
        var mapper = Jackson2ObjectMapperBuilder.json().featuresToDisable(WRITE_DATES_AS_TIMESTAMPS).build();
        mvc = MockMvcBuilders.standaloneSetup(new JobPostingController(service))
                .setControllerAdvice(new GlobalExceptionHandler())
                .setMessageConverters(new MappingJackson2HttpMessageConverter(mapper))
                .build();
    }

    @Test
    void paginatesInStableOrderAndSearchesAcrossAllPages() throws Exception {
        List<Integer> inserted = new ArrayList<>();
        inserted.add(posting("Rare 100%_ match", null, null, 0, null));
        for (int i = 1; i <= 40; i++) {
            inserted.add(posting("Rare 100XA match " + i, null, null, 0, null));
        }
        var expected = inserted.reversed();

        assertThat(ids(list().andExpect(jsonPath("$.data.totalElements").value(41))
                .andExpect(jsonPath("$.data.totalPages").value(3))
                .andExpect(jsonPath("$.data.asOfDate").value(LocalDate.now(SEOUL).toString()))))
                .containsExactlyElementsOf(expected.subList(0, 20));
        assertThat(ids(list("page", "1"))).containsExactlyElementsOf(expected.subList(20, 40));
        assertThat(ids(list("page", "2"))).containsExactly(expected.getLast());
        assertThat(ids(list("page", "3").andExpect(jsonPath("$.data.totalElements").value(41)))).isEmpty();
        assertThat(ids(list("keyword", "rare 100%_").andExpect(jsonPath("$.data.totalElements").value(1))))
                .containsExactly(expected.getLast());
        list("keyword", "no match").andExpect(jsonPath("$.data.totalElements").value(0))
                .andExpect(jsonPath("$.data.totalPages").value(0))
                .andExpect(jsonPath("$.data.content").isEmpty());
    }

    @Test
    void combinesCompanyStackAndCareerFiltersWithoutDuplicatePostings() throws Exception {
        company("A");
        company("B");
        int junior = posting("Junior", "A", null, 0, null);
        int both = posting("Any career level", "A", null, 1, "Plain-text imported description");
        int career = posting("Experienced", "A", null, 0, "{\"career\":\"경력\"}");
        int anotherCompany = posting("Another company", "B", null, 2, null);
        stack(junior, 1);
        stack(both, 1);
        stack(both, 2);
        stack(career, 2);
        stack(anotherCompany, 1);

        assertThat(ids(list("cid", "A", "keyword", "ignored", "stackIds", "1,2", "experience", "junior")
                .andExpect(jsonPath("$.data.totalElements").value(2)))).containsExactly(both, junior);
        assertThat(ids(list("cid", "A", "stackIds", "1,2", "experience", "career")
                .andExpect(jsonPath("$.data.totalElements").value(2)))).containsExactly(career, both);
        assertThat(ids(list("cid", "B", "experience", "career"))).containsExactly(anotherCompany);
    }

    @Test
    void filtersCalendarDayBoundariesAndSortsOpenEndedAndExpiredPostings() throws Exception {
        LocalDate today = LocalDate.now(SEOUL);
        int expired = posting("Expired", null, today.minusDays(1).toString(), 0, null);
        int onDay = posting("Ends today", null, today.toString(), 0, null);
        int onSameDay = posting("Also ends today", null, today.toString(), 0, null);
        int dayThree = posting("3 days", null, today.plusDays(3).toString(), 0, null);
        int dayFour = posting("4 days", null, today.plusDays(4).toString(), 0, null);
        int daySeven = posting("7 days", null, today.plusDays(7).toString(), 0, null);
        int dayEight = posting("8 days", null, today.plusDays(8).toString(), 0, null);
        int open = posting("Open-ended", null, null, 0, null);
        int sentinel = posting("Open-ended sentinel", null, "9999-12-31", 0, null);
        int blank = posting("Open-ended blank", null, "", 0, null);
        int invalid = posting("Invalid legacy date", null, "2026-02-30", 0, null);

        assertThat(ids(list("deadline", "urgent"))).containsExactly(dayThree, onSameDay, onDay);
        assertThat(ids(list("deadline", "week"))).containsExactly(daySeven, dayFour);
        assertThat(ids(list("deadline", "relaxed"))).containsExactly(dayEight);
        assertThat(ids(list("deadline", "always"))).containsExactly(invalid, blank, sentinel, open);
        assertThat(ids(list("sort", "deadline"))).containsExactly(
                onSameDay, onDay, dayThree, dayFour, daySeven, dayEight, invalid, blank, sentinel, open, expired);
    }

    @Test
    void rejectsMalformedQueryParameters() throws Exception {
        for (var parameter : List.of(
                List.of("page", "-1"), List.of("page", "2147483647"), List.of("page", "not-a-number"),
                List.of("stackIds", "0"), List.of("stackIds", "1,broken"), List.of("sort", "unknown"),
                List.of("deadline", "unknown"), List.of("experience", "unknown")
        )) {
            mvc.perform(get(LIST_URL).param(parameter.get(0), parameter.get(1)))
                    .andExpect(status().isBadRequest());
        }
    }

    @Test
    void recordsAssociationQueryBaselineForOneAndTwentyPostings() throws Exception {
        for (int i = 0; i < 20; i++) {
            String cid = "company-" + i;
            company(cid);
            stack(posting(i == 0 ? "Baseline single" : "Baseline posting", cid, null, 0, null), 1);
        }

        entityManager.clear();
        sqlCapture.clear();
        list("keyword", "Baseline single").andExpect(jsonPath("$.data.content.length()").value(1));
        var single = sqlCapture.associationQueries();

        entityManager.clear();
        sqlCapture.clear();
        list("keyword", "Baseline").andExpect(jsonPath("$.data.content.length()").value(20));
        var full = sqlCapture.associationQueries();

        System.out.printf("Association SELECT baseline: 1 posting %s, 20 postings %s%n", single, full);
        assertThat(single.stacks()).isEqualTo(1);
        assertThat(full.stacks()).isEqualTo(20);
        assertThat(single.companies()).isPositive();
        assertThat(full.companies()).isGreaterThan(single.companies());
    }

    private ResultActions list(String... parameters) throws Exception {
        var request = get(LIST_URL);
        for (int i = 0; i < parameters.length; i += 2) {
            request.param(parameters[i], parameters[i + 1]);
        }
        return mvc.perform(request).andExpect(status().isOk());
    }

    private List<Integer> ids(ResultActions result) throws Exception {
        return JsonPath.read(result.andReturn().getResponse().getContentAsString(UTF_8), "$.data.content[*].id");
    }

    private int posting(String title, String cid, String endDate, int jobType, String detail) {
        return jdbc.queryForObject("""
                INSERT INTO job_postings (title, cid, end_date, job_type, detail, active, vcnt)
                VALUES (?, ?, ?, ?, ?, 1, 0) RETURNING id
                """, Integer.class, title, cid, endDate, jobType, detail);
    }

    private void company(String cid) {
        jdbc.update("INSERT INTO companies (cid, companies_name) VALUES (?, ?)", cid, cid);
    }

    private void stack(int postingId, int stackId) {
        jdbc.update("INSERT INTO posting_stacks (job_posting_id, stack_id) VALUES (?, ?)", postingId, stackId);
    }

    @TestConfiguration(proxyBeanMethods = false)
    static class SqlCaptureConfig {
        @Bean
        SqlCapture sqlCapture() {
            return new SqlCapture();
        }

        @Bean
        HibernatePropertiesCustomizer captureStatements(SqlCapture sqlCapture) {
            return properties -> properties.put("hibernate.session_factory.statement_inspector", sqlCapture);
        }
    }

    static class SqlCapture implements StatementInspector {
        private final List<String> statements = new ArrayList<>();

        @Override
        public String inspect(String sql) {
            statements.add(sql);
            return sql;
        }

        void clear() {
            statements.clear();
        }

        AssociationQueries associationQueries() {
            long stacks = statements.stream()
                    .filter(sql -> sql.contains("from posting_stacks ") && !sql.contains("from job_postings "))
                    .count();
            long companies = statements.stream().filter(sql -> sql.contains("from companies ")).count();
            return new AssociationQueries(stacks, companies);
        }
    }

    record AssociationQueries(long stacks, long companies) {
    }
}
